<p id="nasa_intro">
	Students from The Ohio State University received an invitation to participate in phase two of
	NASA’s Micro-g Neutral Buoyancy Experiment Design Teams (Micro-g NExT) challenge. This challenge
	tasks students with developing a tool or device needed by NASA to return to the Moon by 2024 for
	their Artemis Program. The tools created by student teams are tested in the Neutral Buoyancy
	Laboratory—a 6.2-million-gallon indoor pool at the Johnson Space Center in Houston, Texas, where
	astronauts train for spacewalks. The Ohio State University chose to tackle the “Orion crew
	safety–Surface Autonomous Vehicle for Emergency Response (SAVER) challenge” this semester. They
	will be sending their device: Surface Autonomous Vehicle for Initial Search and Rescue Response
	(SAVISARR) to NASA for testing in June. The team’s invention could be used in future space
	missions.
</p>

<img src="/assets/img/projects/image4.png" class="rounded-sm my-8 mx-auto" />

<p>
	In the event of an unplanned egress (launch abort, contingency landing, etc.), Orion crew members
	will be exiting the crew vehicle and using a life raft. Each astronaut will be equipped with a
	121.5 MHz emergency distress beacon to ensure they can be located should they be separated from
	the life raft and Orion capsule. The SAVISARR device is sent into the water to search for the
	distress beacon to deliver the astronaut life-saving supplies. This device has been tested at Ohio
	State’s Aquatics Center and will be tested by NASA in June. The tracking system sits on top of a
	2-foot tall antenna tower. The Ohio State University Micro-g NExt team appreciates the willingness
	of the Center for Design and Manufacturing Excellence to assist with this project. CDME 3D printed
	the antenna tower out of carbon fiber and ABS plastic within one week of being provided files.
	Swift manufacturing of this part allowed the construction of the device to continue on schedule.
</p>

<br>

<p class="mb-6">
	Participating in Micro-g NExT allows students to apply knowledge learned in the classroom in order
	to contribute to real NASA missions. Previous student-developed tools have been manufactured and
	used in spacewalks outside the International Space Station. NASA is committed to engaging students
	in work that will enable humans to explore the solar system, as humans head back to the Moon and
	on to Mars. Artemis Student Challenges are managed by NASA’s Office of STEM Engagement. The
	challenges help support the agency’s education policy of using NASA’s unique missions and programs
	to engage and encourage students to pursue science, technology, engineering, and math careers.
</p>

